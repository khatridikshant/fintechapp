/// Bikram Sambat month lengths.
///
/// Each entry is the number of days in each of the twelve BS months, in order
/// from Baishakh. The year's total length is **not** stored: it is the sum, and
/// storing a derived value is how data starts disagreeing with itself.
///
/// ## What this data is
///
/// These are **facts about a published civil calendar**, not code and not anyone's
/// creative work. The Bikram Sambat calendar is set by the Government of Nepal
/// and published by the Nepal Panchanga Nirnayak Samiti. How many days a given
/// Nepali month has is a fact in the same way that how many days are in April is a
/// fact. Facts are not owned by anyone, which is why this table is kept here as
/// first-party data rather than pulled from a dependency.
///
/// ## Why it is not a package
///
/// This data was originally taken from the `bikram_sambat` package, which is
/// MIT licensed. It was brought in-tree so that the fiscal calendar, the single
/// most compliance-critical dataset in the product, does not depend on one
/// maintainer staying available, staying MIT, or staying healthy. See ADR 009.
///
/// ## Coverage
///
/// BS 1969 to BS 2199, which covers AD 1932 to AD 2143.
///
/// The upstream table extended to BS 2200, but that entry is twelve 31-day
/// months totalling 372 days. No calendar year is 372 days, so it is
/// projected placeholder data, not a real calendar. It has been **excluded**
/// rather than carried as though it were authoritative. A fiscal year needing
/// BS 2200 is refused rather than guessed.
///
/// ## Before shipping
///
/// This table should be checked against the officially published Nepali calendar
/// for the years the product will be used in. The data here has been verified for
/// internal consistency and against known public anchors (1 Shrawan 2082 =
/// 17 July 2025), which is not the same as an audit against the government
/// publication. See ADR 009.

